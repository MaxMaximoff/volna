"""Generate Volna's EQ tables (firmware/gen/eq_tables.h) for engine/eq.h, the three-band EQ (Simper's SVF shelves and
bell, on engine/svf.h's tables).

  EQ_A2[d]   A^2 = 10^(dB / 20), Q14, for dB = d - EQ_DBMAX (-12 .. +12, a dB a step): the band's gain
  EQ_A[d]    A   = 10^(dB / 40), Q14: the bell's damping 1 / (Q A), the shelves' m1
  EQ_SA[d]   sqrt(A) = 10^(dB / 80), Q14: the shelves' corner g = tan / sqrt(A) (low), tan x sqrt(A) (high)

    python3 tools/gen_eq.py            (writes firmware/gen/eq_tables.h)
    python3 tools/gen_eq.py --check    (exit 1 if the header is not what this script makes)
"""
import sys
from pathlib import Path

DBMAX = 12
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "eq_tables.h"


def q14(x):
    return int(round(x * (1 << 14)))


def header():
    dbs = range(-DBMAX, DBMAX + 1)

    def table(name, f):
        vals = [q14(f(d)) for d in dbs]
        rows = ["    " + ", ".join(f"{v}u" for v in vals[i:i + 13]) + "," for i in range(0, len(vals), 13)]
        return f"static const uint16_t {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"

    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_eq.py: do not edit. The EQ's gains (engine/eq.h), Q14, for -12 .. +12 dB (index\n"
        " * dB + EQ_DBMAX): EQ_A2 = 10^(dB/20), EQ_A = 10^(dB/40), EQ_SA = 10^(dB/80). */\n"
        "#ifndef EQ_TABLES_H\n#define EQ_TABLES_H\n#include <stdint.h>\n"
        f"#define EQ_DBMAX {DBMAX}\n" +
        table("EQ_A2", lambda d: 10 ** (d / 20)) + table("EQ_A", lambda d: 10 ** (d / 40)) +
        table("EQ_SA", lambda d: 10 ** (d / 80)) +
        "#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("eq_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_eq.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
