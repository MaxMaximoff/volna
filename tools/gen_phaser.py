"""Generate Volna's phaser tables (firmware/gen/phaser_tables.h) for engine/fx.h, PHASER.

  PH_G[i]    the allpass stages' coefficient G = g / (1 + g), g = tan(pi f / 44100), Q30, every half semitone:
             i = 2 n for the note n = 0 .. 133 (as svf.h's SVF_G; f = 440 * 2^((n - 69) / 12))
  for the screen (ui.h: the response drawn, no float):
  PH_AT[k]   one stage's phase lag at f / fc = 2^((k - 132) / 22), k = 0 .. 264 (+-6 octaves, a pixel of the
             filter's axis a step): 2 atan(f / fc), in 1/65536 of a turn (0 .. 32768: up to half a turn)
  PH_COS[i]  cos(2 pi i / 256), Q14, i = 0 .. 256

    python3 tools/gen_phaser.py            (writes firmware/gen/phaser_tables.h)
    python3 tools/gen_phaser.py --check    (exit 1 if the header is not what this script makes)
"""
import math
import sys
from pathlib import Path

FS = 44100
GN = 2 * 133 + 1
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "phaser_tables.h"


def freq(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def header():
    def g_of(i):
        g = math.tan(math.pi * freq(i / 2) / FS)
        return int(round(g / (1 + g) * (1 << 30)))

    gs = [g_of(i) for i in range(GN)]
    at = [int(round(2 * math.atan(2.0 ** ((k - 132) / 22.0)) / (2 * math.pi) * 65536)) for k in range(265)]
    cs = [int(round(math.cos(2 * math.pi * i / 256) * 16384)) for i in range(257)]

    def table(ctype, name, vals, per=8, suf="u"):
        rows = ["    " + ", ".join(f"{v}{suf}" for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]
        return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"

    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_phaser.py: do not edit. PHASER's tables (engine/fx.h, ui.h):\n"
        " * PH_G: G = g / (1 + g), g = tan(pi f / 44100), Q30, every half semitone of notes 0..133;\n"
        " * PH_AT: 2 atan(f / fc) in 1/65536 turn for f / fc = 2^((k - 132) / 22); PH_COS: cos, Q14, 256 a turn. */\n"
        "#ifndef PHASER_TABLES_H\n#define PHASER_TABLES_H\n#include <stdint.h>\n" +
        table("uint32_t", "PH_G", gs) + table("uint16_t", "PH_AT", at, 12) + table("int16_t", "PH_COS", cs, 12, "") +
        "#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("phaser_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_phaser.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
