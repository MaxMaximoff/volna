# Volna's cut (fm-firmwares): TTF only, always trimmed, tabular digits by hand, three faces.
"""Render Volna's screen fonts (Barlow Semi Condensed, assets/fonts/, SIL OFL 1.1) to firmware/gen/barlow_font.h.
And the splash's wordmark, VOLNA, as one picture (WORDS).

    python3 tools/gen_font.py            write the header
    python3 tools/gen_font.py --check    exit 1 if the header is not what this script makes

From fm1-base's tools/gen_font.py (reference/fm1-base, MPL-2.0), its FM1_FONT_TRIM layout. Glyph format: per glyph an
advance, the lit box's width (BW) and an offset; at the offset the box's left column (from FONT_PAD left of the pen),
top row and row count, a byte each, then the rows, 2 pixels a byte (high nibble first), alpha 0..15. The face's
`trim` is 1: gfx.c draws it so; Terminus (felucca_font.h, the platform's screens) stays untrimmed, trim 0.

The digits all get the widest digit's advance, centred in it: a value does not jump sideways as it counts. The
rendering is FreeType's through Pillow: generate on the build machine (WSL venv), --check there too.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
OUT = ROOT / "firmware" / "gen" / "barlow_font.h"
PAD = 2
# (name, file, px, first, last): the roles ui.h draws with
FACES = [
    ("SM", "BarlowSemiCondensed-SemiBold.ttf", 12, 32, 126),   # cell labels, units, hints, scales
    ("MD", "BarlowSemiCondensed-SemiBold.ttf", 16, 32, 126),   # the pictures' text, the footer, lists
    ("LG", "BarlowSemiCondensed-SemiBold.ttf", 27, 32, 95),    # the cells' values, the lens (no lower case)
]
# (name, text, file, px, tracking): a word as one picture (the splash's wordmark: no big face for 5 letters)
WORDS = [("SPLASH", "VOLNA", "BarlowSemiCondensed-SemiBold.ttf", 50, 4)]


def render(ttf, px, first, last):
    font = ImageFont.truetype(str(FONTS / ttf), px)
    asc, desc = font.getmetrics()
    top = max(0, font.getbbox("A8|(")[1] - 1)          # rows above the tallest ink are dropped
    h = asc + desc - top
    digits = [int(round(font.getlength(str(d)))) for d in range(10)]
    dadv = max(digits)
    glyphs = []
    for c in range(first, last + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch)))
        shift = 0
        if ch.isdigit():                                 # tabular: centred in the widest digit
            shift = (dadv - adv) // 2
            adv = dadv
        bw = adv + 2 * PAD
        img = Image.new("L", (bw + 4, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD + shift, 0), ch, font=font, fill=255)
        img = img.crop((0, top, bw + 4, top + h))
        glyphs.append((adv, bw + 4, [min(15, (v + 8) // 17) for v in img.tobytes()]))
    return h, glyphs


def lit_box(g, bw, h):
    """a glyph's lit box: (left column, top row, width, rows); (0, 0, 0, 0) for a blank one"""
    rows = [y for y in range(h) if any(g[y * bw:(y + 1) * bw])]
    cols = [x for x in range(bw) if any(g[y * bw + x] for y in range(h))]
    if not rows:
        return 0, 0, 0, 0
    return cols[0], rows[0], cols[-1] - cols[0] + 1, rows[-1] - rows[0] + 1


def word(text, ttf, px, track):
    """a word's lit box, letters spaced by track px: (w, h, alphas 0..15 row by row)"""
    font = ImageFont.truetype(str(FONTS / ttf), px)
    w = int(sum(font.getlength(c) for c in text)) + track * len(text) + 8
    img = Image.new("L", (w, px * 2), 0)
    d, x = ImageDraw.Draw(img), 4.0
    for c in text:
        d.text((x, 0), c, font=font, fill=255)
        x += font.getlength(c) + track
    g = [min(15, (v + 8) // 17) for v in img.tobytes()]
    x0, y0, bw, n = lit_box(g, w, px * 2)
    return bw, n, [g[y * w + x] for y in range(y0, y0 + n) for x in range(x0, x0 + bw)]


def header():
    lines = ["/* generated by tools/gen_font.py from assets/fonts/BarlowSemiCondensed-*.ttf (SIL OFL 1.1): Volna's screen */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, ttf, px, first, last in FACES:
        h, glyphs = render(ttf, px, first, last)
        data, offs, bws = [], [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            x0, y0, w, n = lit_box(g, bw, h)
            data += [x0, y0, n]
            bws.append(w)
            for y in range(y0, y0 + n):
                row = g[y * bw + x0:y * bw + x0 + w] + [0]
                for x in range(0, w, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" +
                     ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(map(str, bws)) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {PAD}, {first}, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA, 1 }};  "
                     f"/* {ttf} {px} px, {len(data)} B */")
        lines.append("")
    for name, text, ttf, px, track in WORDS:
        w, h, a = word(text, ttf, px, track)
        data = []
        for y in range(h):
            row = a[y * w:(y + 1) * w] + [0]
            data += [(row[x] << 4) | row[x + 1] for x in range(0, w, 2)]
        lines.append(f"#define WORD_{name}_W {w}  /* \"{text}\", {ttf} {px} px, letters {track} px apart */")
        lines.append(f"#define WORD_{name}_H {h}")
        lines.append(f"static const uint8_t WORD_{name}[{len(data)}] = {{  /* rows, 2 pixels a byte (high first), alpha 0..15 */")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("barlow_font.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_font.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    for l in text.splitlines():
        if l.startswith("static const felucca_font_t"):
            print(l.split("=")[0].split()[-1], "h", l.split("{")[1].split(",")[0].strip(), l.split("/*")[1].strip(" */"))
