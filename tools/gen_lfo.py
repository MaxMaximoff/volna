"""Generate Volna's LFO rate table (firmware/gen/lfo_tables.h) for engine/mod.h.

An LFO runs a step every ENV_SUB = 16 samples at 44.1 kHz, its phase 32 bits a cycle:
  LFO_INC[x]  the phase step for RATE x = 0..127: f = 0.02 Hz * 2500^(x / 127), 0.02 Hz (50 s a cycle) .. 50 Hz,
              exponential (64 ~ 1 Hz).
  LFO_SYNC_K  for a tempo-synced LFO: the step is LFO_SYNC_K * BPM / (5 * clock ticks a cycle), so that
              2^32 * 16 / 44100 * BPM * 24 / 60 / ticks fits 32-bit arithmetic (no 64-bit division on the chip).

    python3 tools/gen_lfo.py            (writes firmware/gen/lfo_tables.h)
    python3 tools/gen_lfo.py --check    (exit 1 if the header is not what this script makes)
"""
import sys
from pathlib import Path

FS, SUB = 44100, 16
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "lfo_tables.h"
UNIT = (1 << 32) * SUB / FS                     # the step of 1 Hz


def hz(x):
    return 0.02 * 2500.0 ** (x / 127.0)


def header():
    inc = [int(round(hz(x) * UNIT)) for x in range(128)]
    rows = ["    " + ", ".join(f"{v}u" for v in inc[i:i + 8]) + "," for i in range(0, 128, 8)]
    sync_k = int(round(UNIT * 2))               # x BPM / (5 x ticks) = UNIT x BPM x 24 / 60 / ticks
    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_lfo.py: do not edit. LFO phase steps (32 bits a cycle, a step every 16 samples):\n"
        f" * RATE 0..127 = 0.02 .. 50 Hz exponential (32 ~ {hz(32):.2f} Hz, 64 ~ {hz(64):.2f} Hz, 96 ~ {hz(96):.1f} Hz);\n"
        " * synced: LFO_SYNC_K x BPM / (5 x ticks a cycle). */\n"
        "#ifndef LFO_TABLES_H\n#define LFO_TABLES_H\n#include <stdint.h>\n"
        f"#define LFO_SYNC_K {sync_k}u\n"
        "static const uint32_t LFO_INC[128] = {\n" + "\n".join(rows) + "\n};\n#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("lfo_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_lfo.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
