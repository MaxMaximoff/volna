"""Generate Volna's filter tables (firmware/gen/svf_tables.h) for engine/svf.h, the state-variable filter
(the zero-delay-feedback "TPT" SVF, A. Simper / Cytomic).

  SVF_G[i]     g = tan(pi f / 44100), Q28, every half semitone: i = 2 n for the cutoff note n = 0 .. 133
               (f = 440 * 2^((n - 69) / 12), MIDI note numbers: 0 = 8.18 Hz, 132 = 16.7 kHz); the filter
               interpolates linearly between them: within 0.25 cent up to 4 kHz, 4 cents at 16 kHz.
  SVF_K[r]     the damping k = 1 / Q, Q14, for the resonance r = 0..127: Q = 0.5 * 50^(r / 127), from 0.5 (no
               peak) to 25; 0.707 (Butterworth) near r = 11.
  SVF_COMP[r]  the low- and high-pass outputs' level, Q15: min(1, 1 / sqrt(Q)). Their peak is about Q: this keeps
               it near sqrt(Q) (+14 dB at most) and the passband falls as the resonance rises, as in analog filters.

    python3 tools/gen_svf.py            (writes firmware/gen/svf_tables.h)
    python3 tools/gen_svf.py --check    (exit 1 if the header is not what this script makes)
"""
import math
import sys
from pathlib import Path

FS = 44100
GN = 2 * 133 + 1                                # half semitones 0..133: the top (132) interpolates towards 132.5
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "svf_tables.h"


def freq(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def q_of(r):
    return 0.5 * 50.0 ** (r / 127.0)


def tables():
    g = [int(round(math.tan(math.pi * freq(i / 2) / FS) * (1 << 28))) for i in range(GN)]
    k = [int(round((1 << 14) / q_of(r))) for r in range(128)]
    comp = [int(round(min(1.0, 1.0 / math.sqrt(q_of(r))) * 32768)) for r in range(128)]
    return g, k, comp


def header():
    g, k, comp = tables()

    def table(ctype, name, vals, per=8):
        rows = ["    " + ", ".join(f"{v}u" for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]
        return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"

    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_svf.py: do not edit. The state-variable filter's tables (engine/svf.h):\n"
        " * SVF_G: tan(pi f / 44100) Q28 every half semitone of the cutoff, notes 0..133 (8.18 Hz .. 17.7 kHz);\n"
        " * SVF_K: 1 / Q, Q14, for the resonance 0..127 (Q 0.5 .. 25, 0.707 near 11); SVF_COMP: the LP/HP level,\n"
        " * Q15, min(1, 1/sqrt(Q)). */\n"
        "#ifndef SVF_TABLES_H\n#define SVF_TABLES_H\n#include <stdint.h>\n"
        f"#define SVF_GN {GN}u\n" +
        table("uint32_t", "SVF_G", g) + table("uint16_t", "SVF_K", k, 16) + table("uint16_t", "SVF_COMP", comp, 16) +
        "#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("svf_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_svf.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
