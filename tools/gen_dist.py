"""Generate Volna's distortion tables (firmware/gen/dist_tables.h) for engine/fx.h (the DIST effect):
  DIST_TANH[257]  tanh over -4 .. +4 in 1/32 steps, Q15 (32767 = 1): SOFT and TUBE read it, linear between entries;
  DIST_GAIN[128]  DRIVE 0..127 as a gain, Q8: 2^(6 x / 127), x 1 .. x 64 (+36 dB), exponential.

    python3 tools/gen_dist.py            (writes firmware/gen/dist_tables.h)
    python3 tools/gen_dist.py --check    (exit 1 if the header is not what this script makes)
"""
import math
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "dist_tables.h"


def rows(vals, per, fmt):
    return "\n".join("    " + ", ".join(fmt(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))


def header():
    th = [int(round(32767 * math.tanh((i - 128) / 32.0))) for i in range(257)]
    gn = [int(round(256 * 2.0 ** (6.0 * x / 127.0))) for x in range(128)]
    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_dist.py: do not edit. DIST_TANH: tanh(-4 .. 4), 1/32 a step, Q15;\n"
        f" * DIST_GAIN: DRIVE 0..127 -> 2^(6 x / 127), Q8 (x 1 .. x {gn[127] / 256:.0f}; 64 ~ x {gn[64] / 256:.1f}). */\n"
        "#ifndef DIST_TABLES_H\n#define DIST_TABLES_H\n#include <stdint.h>\n"
        "static const int16_t DIST_TANH[257] = {\n" + rows(th, 12, str) + "\n};\n"
        "static const uint16_t DIST_GAIN[128] = {\n" + rows(gn, 12, lambda v: f"{v}u") + "\n};\n#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("dist_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_dist.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
