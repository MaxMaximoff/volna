"""Generate Volna's LO-FI tables (firmware/gen/lofi_tables.h) for engine/fx.h, LO-FI.

  LF_INC[p]   RATE p = 0..127: the hold's step a sample, Q31 (2^31: every sample): 40^(-p / 127), 44.1 kHz .. 1.1 kHz
  LF_HZ[p]    that rate, Hz (the screen)
  LF_STEP[p]  BITS p = 0..127: the quantiser's step, Q8 of a full-scale sample: 2^(14 p / 127), 16 .. 2 bits
              (fx.h scales it to the sound's envelope)

    python3 tools/gen_lofi.py            (writes firmware/gen/lofi_tables.h)
    python3 tools/gen_lofi.py --check    (exit 1 if the header is not what this script makes)
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "lofi_tables.h"


def header():
    inc = [min((1 << 31), int(round((1 << 31) * 40.0 ** (-p / 127)))) for p in range(128)]
    hz = [int(round(44100 * 40.0 ** (-p / 127))) for p in range(128)]
    step = [int(round(256 * 2.0 ** (14 * p / 127))) for p in range(128)]

    def table(ctype, name, vals, per=8):
        rows = ["    " + ", ".join(f"{v}u" for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]
        return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"

    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_lofi.py: do not edit. LO-FI's tables (engine/fx.h, ui.h):\n"
        " * LF_INC: the hold's step a sample, Q31, 40^(-p/127) (44.1 .. 1.1 kHz); LF_HZ: that rate in Hz;\n"
        " * LF_STEP: the quantiser's step, Q8 of full scale, 2^(14 p / 127) (16 .. 2 bits; fx.h: of the envelope). */\n"
        "#ifndef LOFI_TABLES_H\n#define LOFI_TABLES_H\n#include <stdint.h>\n" +
        table("uint32_t", "LF_INC", inc) + table("uint16_t", "LF_HZ", hz, 12) + table("uint32_t", "LF_STEP", step) +
        "#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("lofi_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_lofi.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
