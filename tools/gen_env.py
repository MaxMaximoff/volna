"""Generate Volna's envelope tables (firmware/gen/env_tables.h).

An envelope parameter 0..127 is a time from 1 ms to 10 s, exponentially (64 ~ 100 ms). The envelope runs a step
every ENV_SUB = 16 samples at 44.1 kHz, its level Q30 (1 << 30 = full):
  ENV_ATK[x]   the attack's linear increment a step: 0 -> full in time(x);
  ENV_COEF[x]  the decay's and the release's multiplier a step, Q30: the distance left falls to 1/1000 (-60 dB)
               in time(x).

    python3 tools/gen_env.py            (writes firmware/gen/env_tables.h)
    python3 tools/gen_env.py --check    (exit 1 if the header is not what this script makes)
"""
import math
import sys
from pathlib import Path

FS, SUB, FULL = 44100, 16, 1 << 30
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "env_tables.h"


def time_ms(x):
    return 10000.0 ** (x / 127.0)                 # 1 ms .. 10 s


def steps(x):
    return max(1.0, time_ms(x) * FS / 1000.0 / SUB)


def header():
    atk = [min(FULL, math.ceil(FULL / steps(x))) for x in range(128)]
    coef = [int(round(FULL * math.exp(math.log(0.001) / steps(x)))) for x in range(128)]
    ms = [time_ms(x) for x in range(128)]

    def table(name, vals):
        rows = ["    " + ", ".join(f"{v}u" for v in vals[i:i + 8]) + "," for i in range(0, 128, 8)]
        return f"static const uint32_t {name}[128] = {{\n" + "\n".join(rows) + "\n};\n"

    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* generated by tools/gen_env.py: do not edit. Envelope times 0..127 = 1 ms .. 10 s (exponential;\n"
        f" * 32 ~ {ms[32]:.0f} ms, 64 ~ {ms[64]:.0f} ms, 96 ~ {ms[96]:.0f} ms), a step every 16 samples, level Q30. */\n"
        "#ifndef ENV_TABLES_H\n#define ENV_TABLES_H\n#include <stdint.h>\n"
        "/* attack: the increment a step, 0 -> 1 << 30 in the time */\n" + table("ENV_ATK", atk) +
        "/* decay, release: the multiplier a step (Q30), the distance left down to 1/1000 in the time */\n" +
        table("ENV_COEF", coef) + "#endif\n"
    )


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("env_tables.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_env.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT)
