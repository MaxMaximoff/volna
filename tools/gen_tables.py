"""Generate Volna's own wavetables (firmware/gen/wt_public.h), with their mip-maps (tools/wt_mip.py). Stage 8.

Six tables of 64 waves, all made here from formulas (nothing from another synth's ROM: they can be published):
  BASIC  sine (0) -> sawtooth (63): the harmonics 1/k fade in one by one, their count exponential (stage 1's table,
         the same waves)
  PULSE  a pulse wave, its width from 50 % (a square) down to 3 %
  SYNC   a sawtooth hard-synced to the cycle, the synced one's frequency from x 1 up to x 8 (exponential)
  VOICE  vowels A E I O U in a row, the formants of each (Peterson & Barney's male averages) on a 110 Hz voice,
         moving smoothly from one vowel to the next
  FM     two sines, the modulator at the carrier's frequency, the index from 0 up to 8
  FOLD   a sine through a wavefolder (the DIST effect's FOLD), its gain from 1 up to 6
Each wave is band-limited to 63 harmonics and normalised to the same peak (30000).

    python3 tools/gen_tables.py            (writes firmware/gen/wt_public.h; ~half a minute: pure Python)
    python3 tools/gen_tables.py --check    (exit 1 if the header is not what this script makes)
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wt_mip  # noqa: E402

WAVES, LEN, PEAK = 64, 128, 30000
DENSE = 1024                                    # a cycle drawn this fine before its 63 harmonics are taken
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "wt_public.h"


def norm(x):
    pk = max(abs(v) for v in x) or 1.0
    return [v * PEAK / pk for v in x]


def from_cycle(f):
    """a wave from a function of the phase 0..1 (any shape): its 63 harmonics, drawn at 128 samples, normalised"""
    spec = wt_mip.spectrum([f(i / DENSE) for i in range(DENSE)], 63)
    return norm(wt_mip.synth(spec, LEN, 63))


def basic(w):                                   # (as stage 1's tools/gen_wavetable.py: the same waves)
    n = 63 ** (w / (WAVES - 1))
    s = [0.0] * LEN
    for k in range(1, 64):
        g = min(1.0, max(0.0, n - k + 1.0))
        if g == 0.0:
            break
        for i in range(LEN):
            s[i] += g / k * math.sin(2.0 * math.pi * k * i / LEN)
    pk = max(abs(v) for v in s)
    return [float(int(round(v * PEAK / pk))) for v in s]


def pulse(w):
    d = 0.5 - 0.47 * w / (WAVES - 1)
    return from_cycle(lambda p: (1.0 if p < d else 0.0) - d)


def sync(w):
    r = 8.0 ** (w / (WAVES - 1))
    return from_cycle(lambda p: 2.0 * ((p * r) % 1.0) - 1.0)


VOWELS = [(730, 1090, 2440), (530, 1840, 2480), (270, 2290, 3010), (570, 840, 2410), (300, 870, 2240)]   # A E I O U


def voice(w):
    t = w / (WAVES - 1) * (len(VOWELS) - 1)
    i = min(int(t), len(VOWELS) - 2)
    u = t - i
    fm = [a + (b - a) * u for a, b in zip(VOWELS[i], VOWELS[i + 1])]
    spec = []
    for k in range(1, 64):
        f = 110.0 * k
        a = sum(g / (1.0 + ((f - F) / bw) ** 2) for F, bw, g in zip(fm, (90, 110, 150), (1.0, 0.6, 0.3)))
        a *= k ** -0.3                          # the glottis: a soft tilt down
        ph = math.pi * k * k / 63.0             # (Schroeder's phases: a low peak for its loudness)
        spec.append((a * math.cos(ph), a * math.sin(ph)))
    return norm(wt_mip.synth(spec, LEN, 63))


def fm(w):
    ix = 8.0 * (w / (WAVES - 1)) ** 1.5
    return from_cycle(lambda p: math.sin(2 * math.pi * p + ix * math.sin(2 * math.pi * p)))


def fold(w):
    g = 1.0 + 5.0 * w / (WAVES - 1)

    def f(p):
        x = g * math.sin(2 * math.pi * p) + 1.0     # a triangle of period 4: up to 1, back down to -1, ...
        t = x % 4.0
        return t - 1.0 if t < 2.0 else 3.0 - t
    return from_cycle(f)


TABLES = [("BASIC", basic), ("PULSE", pulse), ("SYNC", sync), ("VOICE", voice), ("FM", fm), ("FOLD", fold)]


def header():
    parts = ["/* SPDX-License-Identifier: GPL-3.0-only */\n"
             "/* generated by tools/gen_tables.py: do not edit. Volna's own wavetables, 64 waves each, with their\n"
             " * mip-maps (tools/wt_mip.py, engine/wt_osc.h): " + ", ".join(n for n, _ in TABLES) + ". */\n"
             "#ifndef WT_PUBLIC_H\n#define WT_PUBLIC_H\n#include <stdint.h>\n"
             f"#define WT_PUB_N {len(TABLES)}\n"
             "static const char *const WT_PUB_NAME[WT_PUB_N] = {" + ", ".join(f'"{n}"' for n, _ in TABLES) + "};\n"
             f"static const int16_t WT_PUB[WT_PUB_N][{wt_mip.WORDS}] = {{\n"]
    for name, f in TABLES:
        parts.append(f"  {{ /* {name} */\n" + wt_mip.table_c([f(w) for w in range(WAVES)]) + "\n  },\n")
    parts.append("};\n#endif\n")
    return "".join(parts)


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("wt_public.h:", "up to date" if ok else "OUT OF DATE (run tools/gen_tables.py)")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print("->", OUT, f"({len(TABLES)} tables, {len(TABLES) * wt_mip.WORDS * 2} bytes)")
